"""Extract lumen's weather country/city table (its `Oe` constant) into a C source.

usage: make_cities.py <lumen app.js> <out .c> <out .h>
"""
import json
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("const Oe=[") + len("const Oe=")
depth, i = 0, start
while True:                       # bracket-match the array literal
    c = src[i]
    depth += c == "["
    depth -= c == "]"
    i += 1
    if depth == 0:
        break
js = src[start:i]
js = re.sub(r"([{,])([A-Za-z_]+):", r'\1"\2":', js)
js = re.sub(r":(-?)\.(\d)", r":\g<1>0.\2", js)      # minified numbers: .5 / -.12
data = sorted(json.loads(js), key=lambda c: c["name"])   # lumen lists them by its own region order


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["/* Generated by tools/make_cities.py from lumen's weather city table. Do not edit. */",
       '#include "cities.h"']
for k, c in enumerate(data):
    rows = ", ".join(f"{{ {cstr(t['name'])}, {float(t['lat'])!r}f, {float(t['lon'])!r}f }}" for t in c["cities"])
    out.append(f"static const city_t c{k}[] = {{ {rows} }};")
out.append("const country_t COUNTRIES[] = {")
for k, c in enumerate(data):
    out.append(f"    {{ {cstr(c['code'])}, {cstr(c['name'])}, c{k}, {len(c['cities'])} }},")
out.append("};")
out.append(f"const int NCOUNTRIES = {len(data)};")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
open(sys.argv[3], "w").write("""/* Generated by tools/make_cities.py. */
#pragma once
typedef struct { const char *name; float lat, lon; } city_t;
typedef struct { const char *code, *name; const city_t *cities; int n; } country_t;
extern const country_t COUNTRIES[];
extern const int NCOUNTRIES;
""")
print("countries:", len(data), "cities:", sum(len(c["cities"]) for c in data))
